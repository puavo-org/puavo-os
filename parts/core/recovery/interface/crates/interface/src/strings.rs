#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_locale_names_its_language_and_others_are_english() {
        assert_eq!(Language::from_locale("fi_FI.UTF-8"), Language::Finnish);
        assert_eq!(Language::from_locale("sv_FI.UTF-8\n"), Language::Swedish);
        assert_eq!(Language::from_locale("de_DE"), Language::German);
        assert_eq!(Language::from_locale("en_GB.UTF-8"), Language::English);
        assert_eq!(Language::from_locale("xx"), Language::English);
    }

    #[test]
    fn every_language_keeps_the_names_of_the_values() {
        let languages = [
            Language::English,
            Language::Finnish,
            Language::Swedish,
            Language::German,
        ];
        for language in languages {
            let strings = Strings::for_language(language);
            let texts_with_values = [
                (strings.passphrase, NETWORK),
                (strings.connecting, NETWORK),
                (strings.queue_place, POSITION),
            ];
            for (text, name) in texts_with_values {
                assert!(text.contains(name), "{language:?}: {text}");
            }
        }
    }
}
