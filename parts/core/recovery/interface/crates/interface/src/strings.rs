//! The texts of the interface in each language, as the boot trust manager
//! keeps its own. A name in braces, such as `{network}`, stands for a value.

/// The names of the values.
pub const NETWORK: &str = "{network}";
pub const POSITION: &str = "{position}";

/// A language the texts are shown in.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Language {
    English,
    Finnish,
    Swedish,
    German,
}

impl Language {
    /// The language of a locale such as `fi_FI.UTF-8`, or English for a
    /// locale without a translation.
    pub fn from_locale(locale: &str) -> Language {
        let locale = locale.trim();
        let name = locale.strip_suffix(".UTF-8").unwrap_or(locale);
        match name {
            "fi_FI" => Language::Finnish,
            "sv_FI" | "sv_SE" => Language::Swedish,
            "de_DE" => Language::German,
            _ => Language::English,
        }
    }
}

impl Strings {
    pub fn for_language(language: Language) -> &'static Strings {
        match language {
            Language::English => &ENGLISH,
            Language::Finnish => &FINNISH,
            Language::Swedish => &SWEDISH,
            Language::German => &GERMAN,
        }
    }
}

